import {test,expect} from 'bun:test';
import {LibrarySync,type LibraryLocal,type LibraryStorage} from './library-sync';
import type {ReadingGateway,Selection} from './progress';
import {AppFailure} from '$lib/shared/domain/failure';
test('offline choices survive retry and conflicts require an explicit choice',async()=>{
 const records=new Map<string,LibraryLocal>();
 const storage:LibraryStorage={read:async(account,title)=>structuredClone(records.get(account+title)||null),write:async row=>{records.set(row.account+row.selection.titleId,structuredClone(row));},replace:async(row,expected)=>{if((records.get(row.account+row.selection.titleId)?.changeId||'')!==expected)return false;records.set(row.account+row.selection.titleId,structuredClone(row));return true;},list:async account=>structuredClone([...records.values()].filter(row=>row.account===account))};
 let online=false,cloud:Selection={titleId:'title',status:'reading',favorite:false,preferredTeamId:'',notify:true,version:1},writes=0;
 const gateway={save:async(account:string,input:Selection)=>{if(!online)throw new AppFailure('network');if(input.version!==cloud.version)throw new AppFailure('conflict');cloud={...input,version:cloud.version!+1};writes++;},selection:async()=>({...cloud}),account:async()=>'one'} as unknown as ReadingGateway;
 let sequence=0;
 const sync=new LibrarySync(gateway,storage,()=>String(++sequence));
 await sync.remember('one',cloud);
 await sync.save('one',{...cloud,favorite:true});
 expect((await sync.state('one','title'))?.pending).toBe(true);
 online=true;cloud={...cloud,status:'completed',version:2};
 await sync.flush('one');
 expect((await sync.state('one','title'))?.conflict?.status).toBe('completed');
 expect(writes).toBe(0);
 await sync.resolve('one','title',true);
 expect(writes).toBe(1);
 expect(cloud.favorite).toBe(true);
 expect((await sync.state('one','title'))?.pending).toBe(false);
 expect(await sync.state('two','title')).toBeNull();
 const viewModel={...cloud,progress:new Proxy({releaseId:'release'},{}),name:'Title'};
 await sync.save('one',viewModel);
 expect((await sync.state('one','title'))?.pending).toBe(false);
 const stale={...cloud};
 cloud={...cloud,status:'paused',version:cloud.version!+1};
 await sync.remember('one',cloud);
 await sync.save('one',{...stale,notify:false});
 expect((await sync.state('one','title'))?.conflict?.status).toBe('paused');
 expect(cloud.notify).toBe(true);
});
test('an older in-flight response cannot erase a newer pending change from another instance',async()=>{
 const records=new Map<string,LibraryLocal>();
 const storage:LibraryStorage={read:async(account,title)=>structuredClone(records.get(account+title)||null),write:async row=>{records.set(row.account+row.selection.titleId,structuredClone(row));},replace:async(row,expected)=>{if((records.get(row.account+row.selection.titleId)?.changeId||'')!==expected)return false;records.set(row.account+row.selection.titleId,structuredClone(row));return true;},list:async account=>structuredClone([...records.values()].filter(row=>row.account===account))};
 let sequence=0,release!:()=>void,started!:()=>void;
 const waiting=new Promise<void>(resolve=>release=resolve),began=new Promise<void>(resolve=>started=resolve);
 const initial:Selection={titleId:'title',status:'reading',favorite:false,preferredTeamId:'',notify:true,version:1};
 const first={save:async()=>{started();await waiting;},selection:async()=>({...initial,favorite:true,version:2})} as unknown as ReadingGateway;
 const second={save:async()=>{throw new AppFailure('network');}} as unknown as ReadingGateway;
 const firstSync=new LibrarySync(first,storage,()=>String(++sequence)),secondSync=new LibrarySync(second,storage,()=>String(++sequence));
 await firstSync.remember('account',initial);
 const sending=firstSync.save('account',{...initial,favorite:true});
 await began;
 await secondSync.save('account',{...initial,notify:false});
 release();await sending;
 const latest=await secondSync.state('account','title');
 expect(latest?.pending).toBe(true);
 expect(latest?.selection.notify).toBe(false);
 expect(latest?.selection.version).toBe(1);
});
