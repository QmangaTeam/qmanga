#!/usr/bin/env bash
set -euo pipefail
source "$(dirname "$0")/lib.sh"
target_config "${1:?target required}"
load_public_origin
test "$(uname -m)" = aarch64 || { echo 'This deployment is built for Oracle Ampere arm64' >&2; exit 2; }
test "$(stat -c %a "$CONFIG_FILE")" = 600 || { echo 'Environment file must have mode 600' >&2; exit 2; }

if ! docker image inspect qmanga-minio:local >/dev/null 2>&1; then
  docker build -f "$QMANGA_REPO_ROOT/infra/minio.Dockerfile" -t qmanga-minio:local "$QMANGA_REPO_ROOT"
fi
data_compose up -d --wait

# The upstream mc image is no longer reliably available. Pin the official
# arm64 release binary and verify its release digest before using it.
mc="$QMANGA_HOST_ROOT/bin/mc"
mkdir -p "$(dirname "$mc")"
if ! test -x "$mc"; then
  download=$(mktemp "$QMANGA_HOST_ROOT/bin/.mc.XXXXXX")
  trap 'rm -f "$download"' EXIT
  curl --fail --location --silent --show-error \
    'https://github.com/minio/mc/releases/download/RELEASE.2025-08-13T08-35-41Z/mc.linux-arm64.RELEASE.2025-08-13T08-35-41Z' -o "$download"
  printf '%s  %s\n' '14c8c9616cfce4636add161304353244e8de383b2e2752c0e9dad01d4c27c12c' "$download" | sha256sum --check --status
  chmod 755 "$download"
  mv "$download" "$mc"
  trap - EXIT
fi

set -a
# This root-owned 0600 file contains only KEY=value assignments generated by
# the operator; it is never loaded from repository or network content.
source "$CONFIG_FILE"
set +a
case "$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD:$S3_ACCESS_KEY:$S3_SECRET_KEY" in
  *[!a-zA-Z0-9_:.-]*) echo 'MinIO names and credentials must be plain random alphanumerics' >&2; exit 2 ;;
esac
if test "$MINIO_ROOT_USER" = "$S3_ACCESS_KEY"; then
  echo 'Application MinIO account must differ from root' >&2; exit 2
fi

mc_run() {
  docker run --rm --network "qmanga-$DEPLOY_TARGET-data" \
    --mount "type=bind,source=$mc,target=/usr/local/bin/mc,readonly" \
    --mount "type=bind,source=$QMANGA_REPO_ROOT/deploy/minio-policy.json,target=/policy.json,readonly" \
    --env "MC_HOST_qmanga=http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@minio:9000" \
    alpine@sha256:ce64758a109eb420d874a118f87920e625e12d3634e03b4a5573fd9f6e5d3507 \
    /usr/local/bin/mc "$@"
}
mc_run mb --ignore-existing qmanga/qmanga-media
mc_run mb --ignore-existing qmanga/qmanga-source
if ! mc_run admin user info qmanga "$S3_ACCESS_KEY" >/dev/null 2>&1; then
  mc_run admin user add qmanga "$S3_ACCESS_KEY" "$S3_SECRET_KEY"
fi
if ! mc_run admin policy info qmanga qmanga-app >/dev/null 2>&1; then
  mc_run admin policy create qmanga qmanga-app /policy.json
fi
mc_run admin policy attach qmanga qmanga-app --user "$S3_ACCESS_KEY"
docker run --rm --network "qmanga-$DEPLOY_TARGET-data" \
  --mount "type=bind,source=$mc,target=/usr/local/bin/mc,readonly" \
  --env "MC_HOST_application=http://$S3_ACCESS_KEY:$S3_SECRET_KEY@minio:9000" \
  alpine@sha256:ce64758a109eb420d874a118f87920e625e12d3634e03b4a5573fd9f6e5d3507 \
  /usr/local/bin/mc ls application/qmanga-media >/dev/null
echo "$DEPLOY_TARGET data and restricted object-storage account are ready"
